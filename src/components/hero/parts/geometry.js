// PLANE: يميل مستوى الشاشة بزاوية isometric (30°).
// matrix(a b c d e f) تعني: x' = a·x + c·y + e   و   y' = b·x + d·y + f
//   a=.866 b=.5  → المحور الأفقي ينزل لليمين بزاوية 30°
//   c=0    d=1   → المحور العمودي يبقى عمودياً
//   e=90   f=40  → إزاحة المستوى كله (x و y)
export const PLANE = "matrix(.866 .5 0 1 90 40)";

// GROUND: مستوى سطح المكتب (لوحة المفاتيح والماوس)، محوراه ينزلان لليمين ولليسار
export const GROUND = (x, y) => `matrix(.866 .5 -.866 .5 ${x} ${y})`;