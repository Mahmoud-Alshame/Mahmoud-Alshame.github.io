// pad: يحوّل 1 إلى "01" (لترقيم الفصول)
// String(n)         يحوّل الرقم إلى نص
// padStart(2, "0")  يضيف أصفاراً من اليسار حتى يصبح طول النص 2
export const pad = (n) => String(n).padStart(2, "0");

// toList: يحوّل "a, b, c" إلى ["a","b","c"] (للوسوم والمهارات)
export const toList = (s) =>
  (s || "")                 // إن كانت القيمة فارغة نستخدم نصاً فارغاً حتى لا يحدث خطأ
    .split(",")             // نقسم النص عند كل فاصلة
    .map((x) => x.trim())   // نحذف المسافات الزائدة من كل جزء
    .filter(Boolean);       // نحذف الأجزاء الفارغة